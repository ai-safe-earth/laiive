"""Freeze the fixture's vectors, so the vector leg can be tested for free.

Run once, by hand, when `datasets/retrieval/graph.json` or a vector case's
`free_text` changes:

    cd services/retriever
    PYTHONPATH=. uv run --no-sync python -m evals.freeze_embeddings

It costs about fifty short embeddings of `text-embedding-3-small` — cents —
and the result is checked in, after which the retrieval suite needs no OpenAI
key and gives the same answer on every run. The alternative, embedding live in
the test, would make a recall number depend on the weather at the API and put
a key in the way of a suite whose whole point is that CI can hold it.

Two sets of vectors go in the file:

* one per seeded **event**, of the composite text `laiive_shared`'s recipes
  build (the same text production embeds, recorded during a throwaway seed
  rather than reimplemented here — a second copy of that recipe is exactly the
  kind of drift the fixture exists to avoid);
* one per vector **case's `free_text`**, which is what the executor would embed
  at query time.

Both are keyed by a hash of the text, so a text that changes without this
script being re-run misses its key and the seed fails loudly.
"""

import json

from openai import OpenAI

from agent.utils.llm_utils import get_openai_client
from config import settings
from tests import graph_fixture

DIMENSIONS = 1536  # text-embedding-3-small, matching setup_schema's index
DECIMALS = 6  # enough for cosine ranking; full precision doubles the file


def embed(client: OpenAI, texts: list[str]) -> list[list[float]]:
    response = client.embeddings.create(model=settings.embeddings_model, input=texts)
    return [[round(x, DECIMALS) for x in item.embedding] for item in response.data]


def question_texts() -> list[str]:
    path = graph_fixture.DATASET / "vector_cases.json"
    if not path.exists():
        return []
    cases = json.loads(path.read_text(encoding="utf-8"))["test_cases"]
    return [case["free_text"] for case in cases]


def main() -> None:
    recorded: list[str] = []

    def recorder(texts: list[str]) -> list[list[float]]:
        """Records what production would embed, and stores nothing real."""
        recorded.extend(texts)
        return [[0.0] * DIMENSIONS for _ in texts]

    driver = graph_fixture.driver()
    with driver.session(database=graph_fixture.TEST_DATABASE) as session:
        graph_fixture.apply_schema(session)
        graph_fixture.seed(session, embed_texts=recorder)
    driver.close()

    texts = recorded + question_texts()
    print(
        f"embedding {len(texts)} texts ({len(recorded)} events, "
        f"{len(texts) - len(recorded)} questions)"
    )

    client = get_openai_client()
    vectors = {
        graph_fixture.text_key(text): vector
        for text, vector in zip(texts, embed(client, texts))
    }

    out = graph_fixture.DATASET / "embeddings.json"
    out.write_text(
        json.dumps(
            {
                "notes": (
                    "Frozen vectors for the retrieval fixture, keyed by a hash of "
                    "the text embedded. Generated by evals/freeze_embeddings.py; "
                    "do not hand-edit. Valid only for the model below - change it "
                    "and this file has to be regenerated."
                ),
                "model": settings.embeddings_model,
                "dimensions": DIMENSIONS,
                "vectors": vectors,
            }
        ),
        encoding="utf-8",
    )
    print(f"wrote {len(vectors)} vectors to {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
